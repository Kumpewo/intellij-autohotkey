package de.kumpewo.autohotkey.annotation;

import com.intellij.lang.annotation.AnnotationHolder;
import com.intellij.lang.annotation.Annotator;
import com.intellij.lang.annotation.HighlightSeverity;
import com.intellij.openapi.util.TextRange;
import com.intellij.psi.PsiElement;
import com.intellij.psi.PsiErrorElement;
import com.intellij.psi.PsiFile;
import com.intellij.psi.util.PsiTreeUtil;
import de.kumpewo.autohotkey.AhkBundle;
import de.kumpewo.autohotkey.AhkLanguage;
import de.kumpewo.autohotkey.validate.AhkValidation;
import org.jetbrains.annotations.NotNull;

import java.util.Set;

/**
 * Shows the technical parser errors of Grammar-Kit ("&lt;expression&gt; expected, got 'x'") as a generic
 * "Syntax error". The original error elements are hidden by AhkSyntaxErrorFilter. The plugin's own parser
 * messages (see {@link #isTechnical}) stay as they are. If AutoHotkey accepted the unchanged file in its last
 * validation (AhkValidation), the text says so ("Syntax error (AutoHotkey accepts this code)"): then the plugin's
 * parser does not understand the construct.
 * <p>
 * Works on the whole file: an empty error element is highlighted on the next character, which lies outside the
 * element, and an annotation must lie inside the element being annotated.
 */
public class AhkSyntaxErrorAnnotator implements Annotator {

    /** Annotates all technical parser errors of the file (outside lines marked with ";@ignore-next-line"). */
    @Override
    public void annotate(@NotNull PsiElement element, @NotNull AnnotationHolder holder) {
        if (!(element instanceof PsiFile file) || file.getLanguage() != AhkLanguage.INSTANCE) return;
        String message = AhkBundle.message(AhkValidation.isAccepted(file)
                ? "parser.syntax.error.accepted" : "parser.syntax.error");
        for (PsiErrorElement error : PsiTreeUtil.collectElementsOfType(file, PsiErrorElement.class)) {
            if (!isTechnical(error) || AhkIgnoredLines.isIgnored(error)) continue;
            TextRange range = error.getTextRange();
            var builder = holder.newAnnotation(HighlightSeverity.ERROR, message);
            if (!range.isEmpty()) {
                builder.range(range).create();
                continue;
            }
            // Like the platform does for empty error elements, but skipping blanks: the next character in the
            // line, or after the end of the line if the line (or the file) ends here.
            int offset = range.getStartOffset();
            String text = file.getText();
            while (offset < text.length() && (text.charAt(offset) == ' ' || text.charAt(offset) == '\t')) offset++;
            if (offset < text.length() && text.charAt(offset) != '\n' && text.charAt(offset) != '\r') {
                builder.range(new TextRange(offset, offset + 1)).create();
            } else {
                builder.range(new TextRange(offset, offset)).afterEndOfLine().create();
            }
        }
    }

    /**
     * True for a parser error generated by Grammar-Kit, false for the plugin's own parser messages
     * (AhkParserUtil, texts from the bundle), which are meant for the user.
     */
    public static boolean isTechnical(@NotNull PsiErrorElement error) {
        return !OwnMessages.TEXTS.contains(error.getErrorDescription());
    }

    /** The plugin's own parser messages (holder class, no static initialization in extension classes). */
    private static final class OwnMessages {
        static final Set<String> TEXTS = Set.of(
                AhkBundle.message("parser.case.or.default.expected"),
                AhkBundle.message("parser.stray.brace"),
                AhkBundle.message("parser.requires.v21"));
    }
}
